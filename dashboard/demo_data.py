def lab_addresses(rows: list[dict[str, object]], *keys: str) -> bool:
    """Kayıtlardaki IP alanlarının 10.0.0.0/16 laboratuvar aralığında olduğunu doğrular."""
    for row in rows:
        for key in keys:
            address = str(row[key])
            if not address.startswith("10.0."):
                return False
    return True
